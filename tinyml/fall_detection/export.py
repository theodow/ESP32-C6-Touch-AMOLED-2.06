"""int8 TFLite conversion and C source export for TensorFlow Lite Micro."""

from __future__ import annotations

import tempfile
from pathlib import Path

import numpy as np
import tensorflow as tf


def to_int8_tflite(model: tf.keras.Model, representative: np.ndarray) -> bytes:
    """Full-integer quantization: int8 weights, activations, input and output."""
    def rep_data():
        for i in range(len(representative)):
            yield [representative[i : i + 1].astype(np.float32)]

    # Keras 3 models go through a SavedModel export; converting a tf.function
    # directly leaves resource variables the calibrator cannot read.
    with tempfile.TemporaryDirectory() as tmp:
        model.export(tmp, format="tf_saved_model", verbose=False)
        converter = tf.lite.TFLiteConverter.from_saved_model(tmp)
        converter.optimizations = [tf.lite.Optimize.DEFAULT]
        converter.representative_dataset = rep_data
        converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        converter.inference_input_type = tf.int8
        converter.inference_output_type = tf.int8
        return converter.convert()


def run_tflite(tflite_model: bytes, x: np.ndarray) -> np.ndarray:
    """Run the int8 model on float inputs the same way the firmware will; returns fall probabilities."""
    interp = tf.lite.Interpreter(model_content=tflite_model)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    in_scale, in_zp = inp["quantization"]
    out_scale, out_zp = out["quantization"]
    probs = np.empty(len(x), np.float32)
    for i in range(len(x)):
        q = np.clip(np.round(x[i : i + 1] / in_scale + in_zp), -128, 127).astype(np.int8)
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        probs[i] = (interp.get_tensor(out["index"]).astype(np.float32).ravel()[0] - out_zp) * out_scale
    return probs


def tflite_io_quant(tflite_model: bytes) -> tuple[float, int, float, int]:
    interp = tf.lite.Interpreter(model_content=tflite_model)
    in_scale, in_zp = interp.get_input_details()[0]["quantization"]
    out_scale, out_zp = interp.get_output_details()[0]["quantization"]
    return float(in_scale), int(in_zp), float(out_scale), int(out_zp)


def _fmt_floats(values) -> str:
    return ", ".join(f"{v:.6f}f" for v in values)


def write_c_sources(
    out_dir: Path,
    tflite_model: bytes,
    *,
    name: str,
    sample_rate_hz: float,
    window_len: int,
    channel_mean: np.ndarray,
    channel_std: np.ndarray,
    threshold: float,
    tensor_arena_hint: int,
) -> tuple[Path, Path]:
    """Write <name>.h / <name>.cc with the model bytes and everything the firmware needs to feed it."""
    in_scale, in_zp, out_scale, out_zp = tflite_io_quant(tflite_model)
    channels = len(channel_mean)
    guard = f"{name.upper()}_H_"
    header = f"""// Generated by tinyml/fall_detection/train.py - do not edit.
#ifndef {guard}
#define {guard}

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

// Input: {window_len} samples x {channels} channels at {sample_rate_hz:g} Hz.
// Channel order: ax, ay, az [g], gx, gy, gz [deg/s] (QMI8658 m/s^2 / 9.80665).
#define {name.upper()}_SAMPLE_RATE_HZ {int(round(sample_rate_hz))}
#define {name.upper()}_WINDOW_LEN {window_len}
#define {name.upper()}_NUM_CHANNELS {channels}
#define {name.upper()}_TENSOR_ARENA_SIZE {tensor_arena_hint}

// Per-channel standardisation applied before quantisation: x_n = (x - mean) / std
static const float {name}_channel_mean[{channels}] = {{{_fmt_floats(channel_mean)}}};
static const float {name}_channel_std[{channels}] = {{{_fmt_floats(channel_std)}}};

// int8 quantisation of the input / output tensors: q = round(x_n / scale) + zero_point
#define {name.upper()}_INPUT_SCALE {in_scale:.9g}f
#define {name.upper()}_INPUT_ZERO_POINT {in_zp}
#define {name.upper()}_OUTPUT_SCALE {out_scale:.9g}f
#define {name.upper()}_OUTPUT_ZERO_POINT {out_zp}

// Fall if dequantised output probability >= threshold (chosen on the validation set).
#define {name.upper()}_THRESHOLD {threshold:.4f}f

extern const unsigned char {name}_tflite[];
extern const unsigned int {name}_tflite_len;

#ifdef __cplusplus
}}
#endif

#endif  // {guard}
"""
    rows = []
    for i in range(0, len(tflite_model), 12):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in tflite_model[i : i + 12]) + ",")
    source = f"""// Generated by tinyml/fall_detection/train.py - do not edit.
#include "{name}.h"

// TFLM requires the flatbuffer to be 16-byte aligned.
alignas(16) const unsigned char {name}_tflite[] = {{
{chr(10).join(rows)}
}};
const unsigned int {name}_tflite_len = {len(tflite_model)};
"""
    out_dir.mkdir(parents=True, exist_ok=True)
    h, cc = out_dir / f"{name}.h", out_dir / f"{name}.cc"
    h.write_text(header)
    cc.write_text(source)
    return h, cc
